#!/usr/bin/env tsx
/**
 * generate-permission-disposition — build the ORPHAN DISPOSITION REGISTER for
 * GAP-F0-02 (permission catalogue integrity).
 *
 * Catalogue integrity has two halves:
 *   1. every permission REFERENCE in code/SQL resolves to a catalogue pair
 *      (enforced by scripts/verify-rbac-parity.mjs + the coverage generator);
 *   2. every catalogue pair is either REFERENCED somewhere, or carries an
 *      explicit, reviewed DISPOSITION saying why it exists unreferenced.
 *
 * This script produces (2): docs/rbac/permission-disposition.json (machine) and
 * docs/rbac/permission-disposition.md (human). Dispositions are rule-derived so
 * the register cannot silently rot, with a hand-maintained override table for
 * decisions that rules cannot infer.
 *
 * Usage: bunx tsx scripts/generate-permission-disposition.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildCoverage, classifyCoverage, type CatalogEntry } from '../src/lib/rbac/coverageScanner';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Pairs registered purely so historic RLS/RPC access rules resolve. */
const LEGACY_ALIAS = new Set<string>([
  'application_management.close',
  'application_management.configure',
  'application_management.escalate',
  'application_management.import',
  'application_management.review',
  'correspondence_management.approve',
  'correspondence_management.edit',
  'employee_management.view',
  'fit_and_proper.view_confidential',
  'report_management.execute',
  'returns_management.reject',
  'role_management.assign',
  'role_management.manage_config',
]);

/** Explicit overrides: pair → [disposition, rationale]. */
const OVERRIDES: Record<string, [string, string]> = {};

type Disposition = 'legacy-alias' | 'reserved-granular' | 'future-module' | 'manual';

interface Row {
  module: string;
  action: string;
  disposition: Disposition;
  rationale: string;
}

const catalog = JSON.parse(
  readFileSync(join(ROOT, 'src/lib/rbac/catalog.json'), 'utf8'),
) as CatalogEntry[];

const matrix = buildCoverage(ROOT, catalog);
const referencedModules = new Set(
  matrix.rows.filter((r) => classifyCoverage(r) !== 'orphaned').map((r) => r.module),
);

const rows: Row[] = [];
for (const r of matrix.rows) {
  if (classifyCoverage(r) !== 'orphaned') continue;
  const pair = `${r.module}.${r.action}`;
  const override = OVERRIDES[pair];
  if (override) {
    rows.push({ module: r.module, action: r.action, disposition: 'manual', rationale: override[1] });
    continue;
  }
  if (LEGACY_ALIAS.has(pair)) {
    rows.push({
      module: r.module,
      action: r.action,
      disposition: 'legacy-alias',
      rationale:
        'Registered for historic database access rules that check this pair; no role grant exists, so it denies by default.',
    });
    continue;
  }
  if (!referencedModules.has(r.module)) {
    rows.push({
      module: r.module,
      action: r.action,
      disposition: 'future-module',
      rationale:
        'Module has no enforced surface yet; the whole module is catalogued ahead of its build-out and grants nothing today.',
    });
    continue;
  }
  rows.push({
    module: r.module,
    action: r.action,
    disposition: 'reserved-granular',
    rationale:
      'Module is live and enforced through coarser actions; this finer-grained action is reserved for future split-out and grants nothing today.',
  });
}

rows.sort((a, b) => `${a.module}.${a.action}`.localeCompare(`${b.module}.${b.action}`));

const counts = rows.reduce<Record<string, number>>((acc, r) => {
  acc[r.disposition] = (acc[r.disposition] ?? 0) + 1;
  return acc;
}, {});

writeFileSync(
  join(ROOT, 'docs/rbac/permission-disposition.json'),
  JSON.stringify({ generatedFrom: 'src/lib/rbac/catalog.json', counts, rows }, null, 2) + '\n',
);

const md: string[] = [
  '# Permission catalogue — orphan disposition register',
  '',
  '> Generated by `scripts/generate-permission-disposition.ts`. Do not edit by hand;',
  '> change the rules or the `OVERRIDES` table in that script instead.',
  '',
  'An *orphan* is a catalogued `module.action` with no reference in UI guards, route',
  'guards, RLS/RPC policies, storage policies or edge-function gates. Orphans are not',
  'defects by themselves — they must simply be accounted for. None of the pairs below',
  'is granted to any role, role template or user, so none of them widens access.',
  '',
  '| Disposition | Count | Meaning |',
  '| --- | --- | --- |',
  `| legacy-alias | ${counts['legacy-alias'] ?? 0} | Kept so historic database access rules resolve. |`,
  `| reserved-granular | ${counts['reserved-granular'] ?? 0} | Live module, finer-grained action reserved for later split-out. |`,
  `| future-module | ${counts['future-module'] ?? 0} | Module catalogued ahead of its surface being built. |`,
  `| manual | ${counts.manual ?? 0} | Reviewed case-by-case (see rationale). |`,
  '',
  `Total orphans: **${rows.length}**`,
  '',
  '| Permission | Disposition | Rationale |',
  '| --- | --- | --- |',
  ...rows.map((r) => `| \`${r.module}.${r.action}\` | ${r.disposition} | ${r.rationale} |`),
  '',
];
writeFileSync(join(ROOT, 'docs/rbac/permission-disposition.md'), md.join('\n'));

console.log(`permission-disposition: ${rows.length} orphans dispositioned`, counts);
