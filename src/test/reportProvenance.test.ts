import { describe, it, expect } from 'vitest';
import { provenanceFromRun, provenanceLines, reconcileExport } from '@/pages/reports/lib/reportProvenance';

const run = {
  name: 'Prudential breach register',
  category: 'prudential',
  source: 'returns_filed' as never,
  filters: { period: '2026Q1', entity_id: 'ent-1', sector_id: 'sec-1', status: 'submitted', empty: '' },
  rowCount: 3,
  generatedAt: '2026-08-07T10:00:00.000Z',
  generatedBy: 'owner-id',
};

describe('report export provenance', () => {
  it('captures as-of period, entity and regulator from the applied filters', () => {
    const p = provenanceFromRun(run, 'officer@olras.test');
    expect(p.asOfPeriod).toContain('period=2026Q1');
    expect(p.entity).toContain('entity_id=ent-1');
    expect(p.regulator).toContain('sector_id=sec-1');
    expect(p.generatedBy).toBe('officer@olras.test');
    expect(p.generatedAt).toBe('2026-08-07T10:00:00.000Z');
    expect(p.rowCount).toBe(3);
  });

  it('reports All rather than a fabricated scope when a dimension is unfiltered', () => {
    const p = provenanceFromRun({ ...run, filters: {} }, 'officer@olras.test');
    expect(p.asOfPeriod).toBe('All');
    expect(p.entity).toBe('All');
    expect(p.regulator).toBe('All');
  });

  it('drops blank filters from the provenance block', () => {
    const p = provenanceFromRun(run, 'officer@olras.test');
    expect(p.filters.map(([k]) => k)).not.toContain('empty');
  });

  it('emits every governance field required on an exported artefact', () => {
    const keys = provenanceLines(provenanceFromRun(run, 'officer@olras.test')).map(([k]) => k);
    for (const k of ['Report', 'As-of period', 'Entity', 'Regulator / sector', 'Filters', 'Generated by', 'Generated at', 'Rows']) {
      expect(keys).toContain(k);
    }
  });
});

describe('payload-equals-screen reconciliation', () => {
  const screen = [{ id: '1', amount: 10 }, { id: '2', amount: 20 }];

  it('passes when the payload matches the screen exactly', () => {
    expect(reconcileExport(screen, [...screen]).ok).toBe(true);
  });

  it('fails when the payload has fewer rows than the screen', () => {
    const r = reconcileExport(screen, [screen[0]]);
    expect(r.ok).toBe(false);
    expect(r.screenRows).toBe(2);
    expect(r.payloadRows).toBe(1);
  });

  it('fails when the payload adds a column the screen never showed', () => {
    const r = reconcileExport(screen, screen.map((s) => ({ ...s, internal_note: 'x' })));
    expect(r.ok).toBe(false);
    expect(r.extraColumns).toContain('internal_note');
  });

  it('fails when the payload omits a column shown on screen', () => {
    const r = reconcileExport(screen, screen.map((s) => ({ id: s.id })));
    expect(r.ok).toBe(false);
    expect(r.missingColumns).toContain('amount');
  });
});
