/**
 * Phase 11 — governed report export provenance.
 *
 * Every exported artefact must carry the same provenance block that is shown on
 * screen: filters applied, as-of period, entity, regulator, who generated it and
 * when. `reconcile()` proves the exported payload matches the screen (row count
 * and header set) so an export can never silently diverge from the dashboard.
 */
import { supabase } from '@/integrations/supabase/client';
import type { ReportRun } from '../types';

export interface ExportProvenance {
  reportName: string;
  category?: string;
  source?: string;
  asOfPeriod: string;
  entity: string;
  regulator: string;
  filters: Array<[string, string]>;
  generatedBy: string;
  generatedAt: string;
  rowCount: number;
}

const PERIOD_KEYS = ['period', 'as_of', 'asOf', 'period_key', 'date_from', 'dateFrom', 'from', 'to', 'date_to', 'dateTo', 'year', 'quarter'];
const ENTITY_KEYS = ['entity', 'entity_id', 'entityId', 'licensee', 'licensee_id', 'licenseeId'];
const REGULATOR_KEYS = ['regulator', 'regulator_id', 'regulatorId', 'sector', 'sector_id', 'sectorId'];

function pick(filters: Record<string, unknown>, keys: string[]): string {
  const parts: string[] = [];
  for (const k of keys) {
    const v = filters[k];
    if (v == null || v === '' || v === 'all') continue;
    parts.push(`${k}=${typeof v === 'object' ? JSON.stringify(v) : String(v)}`);
  }
  return parts.length ? parts.join('; ') : 'All';
}

export function provenanceFromRun(
  run: Pick<ReportRun, 'name' | 'category' | 'source' | 'filters' | 'rowCount' | 'generatedAt' | 'generatedBy'>,
  generatedBy: string,
): ExportProvenance {
  const filters = (run.filters || {}) as Record<string, unknown>;
  return {
    reportName: run.name,
    category: run.category,
    source: run.source as string | undefined,
    asOfPeriod: pick(filters, PERIOD_KEYS),
    entity: pick(filters, ENTITY_KEYS),
    regulator: pick(filters, REGULATOR_KEYS),
    filters: Object.entries(filters)
      .filter(([, v]) => v != null && v !== '')
      .map(([k, v]) => [k, typeof v === 'object' ? JSON.stringify(v) : String(v)] as [string, string]),
    generatedBy,
    generatedAt: run.generatedAt || new Date().toISOString(),
    rowCount: run.rowCount,
  };
}

/** Resolves the acting user label, then builds the provenance block. */
export async function buildReportProvenance(
  run: Pick<ReportRun, 'name' | 'category' | 'source' | 'filters' | 'rowCount' | 'generatedAt' | 'generatedBy'>,
): Promise<ExportProvenance> {
  let label = run.generatedBy || 'unknown';
  try {
    const { data } = await supabase.auth.getUser();
    label = data.user?.email || data.user?.id || label;
  } catch {
    /* provenance still records the run owner */
  }
  return provenanceFromRun(run, label);
}

export function provenanceLines(p: ExportProvenance): Array<[string, string]> {
  return [
    ['Report', p.reportName],
    ['Category', p.category ?? '—'],
    ['Source', p.source ?? '—'],
    ['As-of period', p.asOfPeriod],
    ['Entity', p.entity],
    ['Regulator / sector', p.regulator],
    ['Filters', p.filters.length ? p.filters.map(([k, v]) => `${k}=${v}`).join('; ') : 'None'],
    ['Generated by', p.generatedBy],
    ['Generated at', p.generatedAt],
    ['Rows', String(p.rowCount)],
  ];
}

export interface ReconcileResult {
  ok: boolean;
  screenRows: number;
  payloadRows: number;
  missingColumns: string[];
  extraColumns: string[];
}

/** Payload-equals-screen reconciliation used before an export is released. */
export function reconcileExport(
  screenRows: Record<string, unknown>[],
  payloadRows: Record<string, unknown>[],
): ReconcileResult {
  const cols = (rows: Record<string, unknown>[]) => {
    const set = new Set<string>();
    rows.forEach((r) => Object.keys(r).forEach((k) => set.add(k)));
    return set;
  };
  const a = cols(screenRows);
  const b = cols(payloadRows);
  const missingColumns = [...a].filter((c) => !b.has(c));
  const extraColumns = [...b].filter((c) => !a.has(c));
  return {
    ok: screenRows.length === payloadRows.length && missingColumns.length === 0 && extraColumns.length === 0,
    screenRows: screenRows.length,
    payloadRows: payloadRows.length,
    missingColumns,
    extraColumns,
  };
}
