/**
 * Permission Coverage Report — read-only admin view of the pre-generated
 * matrix. Rebuild the JSON with:
 *
 *   bunx tsx scripts/generate-permission-coverage.ts
 *
 * We deliberately import a static artifact rather than running the scanner
 * at runtime — the scanner walks the filesystem and is not browser-safe.
 */
import { useMemo, useState } from 'react';
import { DashboardLayout } from '@/components/layout/DashboardLayout';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { Badge } from '@/components/ui/badge';
import { Input } from '@/components/ui/input';
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from '@/components/ui/table';
import { Alert, AlertDescription, AlertTitle } from '@/components/ui/alert';
import { AlertTriangle, Search, ShieldCheck, Lock } from 'lucide-react';
import { classifyCoverage, type CoverageMatrix } from '@/lib/rbac/coverageTypes';
import { useCan } from '@/hooks/useCan';

// The docs artifact is generated by scripts/generate-permission-coverage.ts.
// It is committed under docs/rbac/ and imported here as a static JSON module.
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore -- generated artifact; the file exists after the generator runs.
import coverageJson from '../../../docs/rbac/permission-coverage.json';
const raw = coverageJson as unknown as CoverageMatrix | null;

const EMPTY_MATRIX: CoverageMatrix = { generatedAt: '', rows: [], orphanedCount: 0 };

export default function PermissionCoverageReport() {
  const canViewCoverage = useCan('role_management', 'view_coverage');
  const matrix = (raw ?? EMPTY_MATRIX) as CoverageMatrix;
  const [q, setQ] = useState('');
  const [only, setOnly] = useState<'all' | 'orphaned' | 'ui-only' | 'backend-only' | 'enforced'>('all');

  // Every hook runs before the permission guard so hook order never varies.
  const rows = useMemo(() => {
    const s = q.trim().toLowerCase();
    return matrix.rows.filter((r) => {
      if (only !== 'all' && classifyCoverage(r) !== only) return false;
      if (!s) return true;
      return r.module.toLowerCase().includes(s) || r.action.toLowerCase().includes(s);
    });
  }, [matrix.rows, q, only]);

  if (!canViewCoverage) {
    return (
      <DashboardLayout>
        <Alert variant="destructive" className="max-w-2xl">
          <Lock className="h-4 w-4" />
          <AlertTitle>Access denied</AlertTitle>
          <AlertDescription>
            You need the <code>role_management.view_coverage</code> permission to view the
            Permission Coverage report. Ask an administrator to grant it on your role.
          </AlertDescription>
        </Alert>
      </DashboardLayout>
    );
  }


  const badgeFor = (klass: ReturnType<typeof classifyCoverage>) => {
    switch (klass) {
      case 'orphaned':
        return <Badge variant="destructive">Orphaned</Badge>;
      case 'ui-only':
        return <Badge variant="secondary">UI only</Badge>;
      case 'backend-only':
        return <Badge variant="outline">Backend only</Badge>;
      case 'enforced':
        return <Badge className="bg-green-600 hover:bg-green-600">Enforced</Badge>;
    }
  };

  const filterButtons: { key: typeof only; label: string }[] = [
    { key: 'all', label: 'All' },
    { key: 'enforced', label: 'Enforced' },
    { key: 'backend-only', label: 'Backend only' },
    { key: 'ui-only', label: 'UI only' },
    { key: 'orphaned', label: 'Orphaned' },
  ];

  return (
    <DashboardLayout>
      <div className="space-y-6 p-6">
        <div className="flex items-center gap-3">
          <ShieldCheck className="h-6 w-6 text-primary" />
          <div>
            <h1 className="text-2xl font-semibold">Permission Coverage Matrix</h1>
            <p className="text-sm text-muted-foreground">
              Where every catalogued permission is enforced — Menu, Route, Button, RLS, RPC, Storage, Report.
            </p>
          </div>
        </div>

        {matrix.rows.length === 0 ? (
          <Alert variant="destructive">
            <AlertTriangle className="h-4 w-4" />
            <AlertTitle>Coverage report not generated</AlertTitle>
            <AlertDescription>
              Run <code>bunx tsx scripts/generate-permission-coverage.ts</code> to build{' '}
              <code>docs/rbac/permission-coverage.json</code>, then reload this page.
            </AlertDescription>
          </Alert>
        ) : (
          <>
            <div className="grid grid-cols-2 gap-4 md:grid-cols-4">
              <SummaryCard label="Total permissions" value={matrix.rows.length} />
              <SummaryCard
                label="Enforced (UI + backend)"
                value={matrix.rows.filter((r) => classifyCoverage(r) === 'enforced').length}
              />
              <SummaryCard
                label="Backend only"
                value={matrix.rows.filter((r) => classifyCoverage(r) === 'backend-only').length}
              />
              <SummaryCard label="Orphaned" value={matrix.orphanedCount} tone={matrix.orphanedCount > 0 ? 'danger' : 'ok'} />
            </div>

            {matrix.orphanedCount > 0 && (
              <Alert>
                <AlertTriangle className="h-4 w-4" />
                <AlertTitle>{matrix.orphanedCount} orphaned permission{matrix.orphanedCount === 1 ? '' : 's'}</AlertTitle>
                <AlertDescription>
                  These are catalogued but not enforced anywhere. They cannot be assigned to a role — the
                  database blocks it via the <code>role_permissions_reject_orphaned</code> trigger.
                </AlertDescription>
              </Alert>
            )}

            <Card>
              <CardHeader>
                <CardTitle>Coverage</CardTitle>
                <CardDescription>
                  Last generated: <span className="font-mono text-xs">{matrix.generatedAt || '—'}</span>
                </CardDescription>
              </CardHeader>
              <CardContent className="space-y-4">
                <div className="flex flex-wrap items-center gap-3">
                  <div className="relative">
                    <Search className="pointer-events-none absolute left-2 top-1/2 h-4 w-4 -translate-y-1/2 text-muted-foreground" />
                    <Input
                      value={q}
                      onChange={(e) => setQ(e.target.value)}
                      placeholder="Search module or action…"
                      className="pl-8 w-72"
                    />
                  </div>
                  <div className="flex flex-wrap gap-2">
                    {filterButtons.map((f) => (
                      <button
                        key={f.key}
                        type="button"
                        onClick={() => setOnly(f.key)}
                        className={`rounded-md border px-3 py-1 text-xs ${
                          only === f.key ? 'bg-primary text-primary-foreground' : 'bg-background'
                        }`}
                      >
                        {f.label}
                      </button>
                    ))}
                  </div>
                </div>

                <div className="overflow-x-auto">
                  <Table>
                    <TableHeader>
                      <TableRow>
                        <TableHead>Module</TableHead>
                        <TableHead>Action</TableHead>
                        <TableHead>Coverage</TableHead>
                        <TableHead className="text-right">Menu</TableHead>
                        <TableHead className="text-right">Route</TableHead>
                        <TableHead className="text-right">Button</TableHead>
                        <TableHead className="text-right">RLS</TableHead>
                        <TableHead className="text-right">RPC</TableHead>
                        <TableHead className="text-right">Storage</TableHead>
                        <TableHead className="text-right">Report</TableHead>
                      </TableRow>
                    </TableHeader>
                    <TableBody>
                      {rows.map((r) => (
                        <TableRow key={`${r.module}.${r.action}`}>
                          <TableCell className="font-mono text-xs">{r.module}</TableCell>
                          <TableCell className="font-mono text-xs">{r.action}</TableCell>
                          <TableCell>{badgeFor(classifyCoverage(r))}</TableCell>
                          <TableCell className="text-right tabular-nums">{r.menu.length}</TableCell>
                          <TableCell className="text-right tabular-nums">{r.route.length}</TableCell>
                          <TableCell className="text-right tabular-nums">{r.button.length}</TableCell>
                          <TableCell className="text-right tabular-nums">{r.rls.length}</TableCell>
                          <TableCell className="text-right tabular-nums">{r.rpc.length}</TableCell>
                          <TableCell className="text-right tabular-nums">{r.storage.length}</TableCell>
                          <TableCell className="text-right tabular-nums">{r.report.length}</TableCell>
                        </TableRow>
                      ))}
                    </TableBody>
                  </Table>
                </div>
              </CardContent>
            </Card>
          </>
        )}
      </div>
    </DashboardLayout>
  );
}

function SummaryCard({
  label,
  value,
  tone = 'default',
}: {
  label: string;
  value: number;
  tone?: 'default' | 'ok' | 'danger';
}) {
  const color = tone === 'danger' ? 'text-destructive' : tone === 'ok' ? 'text-green-600' : '';
  return (
    <Card>
      <CardContent className="pt-6">
        <div className="text-xs text-muted-foreground">{label}</div>
        <div className={`text-3xl font-semibold tabular-nums ${color}`}>{value}</div>
      </CardContent>
    </Card>
  );
}
